#!/usr/bin/env python3
"""Pre-flight for the peak-regulatory arm: verify the rewrite's own premises.

Five claims are made about this run. Each is checked here and the outcome is
written to `results/04_peak_regulatory/release_audit/` before any arm runs,
because all of them are cheap to check and expensive to discover afterwards:

  1. VENDOR INTEGRITY -- every vendored file still has the hash recorded when it
     was taken from the previous release. If one has drifted, the run is no
     longer the frozen core plus a known layer, and the result cannot be
     attributed to the data change.
  2. WINDOW SET -- the Astroglia arm sees nine ranking files, and the one it does
     not see is exactly `human-CS18-19_CS20_CS22-23.csv`. A tenth file
     disappearing unnoticed (a typo in a symlink, a failed copy) would shrink the
     analysis without saying so.
  3. RELEASE EDIT -- the cell-level file labels the human Carnegie stage 18-23
     astroglia as `progenitor`, which is the premise of dropping that window.
  4. SOURCE DISAGREEMENT -- the raw matrices still call those cells `astroglia`.
     This is expected and is why the exporter relabels; it is recorded so that
     the disagreement is a documented fact rather than a latent trap.
  5. EXPECTED CONSEQUENCE -- the human early_embryonic window therefore has no
     astroglia pseudobulk, and the other nine windows do.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
VENDOR = PKG / "vendor"
REPO = PKG.parents[1]
MANIFEST = VENDOR / "MANIFEST.json"

sys.path.insert(0, str(REPO / "src"))

EXCLUDED_RANKING = "human-CS18-19_CS20_CS22-23.csv"
EXPECTED_RANKINGS = 9


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_manifest() -> dict:
    if not MANIFEST.exists():
        raise SystemExit(
            f"missing {MANIFEST}. It records the hash of every vendored file and "
            f"is generated by script/write_provenance.py."
        )
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def check_vendor(manifest: dict) -> list[dict]:
    rows = []
    for relative, expected in sorted(manifest["files"].items()):
        path = VENDOR / relative
        if not path.exists():
            rows.append({"check": "vendor", "file": relative, "status": "MISSING",
                         "expected": expected, "observed": ""})
            continue
        observed = sha256(path)
        rows.append({
            "check": "vendor", "file": relative,
            "status": "OK" if observed == expected else "CHANGED",
            "expected": expected, "observed": observed,
        })
    return rows


def check_rankings(config_path: Path) -> tuple[list[dict], list[str]]:
    import yaml

    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    declared = Path(config["paths"]["ranked_dirs"]["astroglia"])
    directory = declared if declared.is_absolute() else (VENDOR / declared)
    files = sorted(p.name for p in directory.glob("*.csv"))
    rows = [{
        "check": "ranking_dir", "file": str(directory),
        "status": "OK" if len(files) == EXPECTED_RANKINGS else "UNEXPECTED",
        "expected": f"{EXPECTED_RANKINGS} files", "observed": f"{len(files)} files",
    }, {
        "check": "ranking_excluded", "file": EXCLUDED_RANKING,
        "status": "OK" if EXCLUDED_RANKING not in files else "PRESENT",
        "expected": "absent from the Astroglia arm",
        "observed": "present" if EXCLUDED_RANKING in files else "absent",
    }]
    return rows, files


def check_cells(h5ad: Path, data_root: Path) -> tuple[list[dict], dict]:
    import anndata as ad
    import numpy as np

    rows: list[dict] = []
    relabelled = ad.read_h5ad(str(h5ad), backed="r")
    try:
        obs = relabelled.obs
        human_cs = (obs["Species"].astype(str).eq("human")
                    & obs["Org_stage"].astype(str).isin(["CS18-19", "CS20", "CS22-23"]))
        is_astro = obs["Celltype"].astype(str).eq("astroglia (progenitors+astrocytes)")
        is_prog = obs["Celltype"].astype(str).eq("progenitor")
        rows += [
            {"check": "cells_relabelled", "file": "human CS18-23",
             "status": "OK" if not (human_cs & is_astro).any() else "FAIL",
             "expected": "0 astroglia at those stages",
             "observed": f"{int((human_cs & is_astro).sum())}"},
            {"check": "cells_relabelled", "file": "progenitor population",
             "status": "OK" if int(is_prog.sum()) == int((is_prog & human_cs).sum()) else "FAIL",
             "expected": "every 'progenitor' cell is human CS18-23",
             "observed": f"{int((is_prog & human_cs).sum()):,} / {int(is_prog.sum()):,}"},
        ]
        counts = {"relabelled_h5ad_progenitor": int(is_prog.sum())}
    finally:
        relabelled.file.close()

    # what the raw matrices still say -- expected to disagree
    raw = data_root / "all_species_h5ad" / "human_deepcerevo_2026.h5ad"
    if raw.exists():
        import h5py

        with h5py.File(raw, "r") as handle:
            group = handle["obs"]["Org_Celltype"]
            categories = [c.decode() if isinstance(c, bytes) else str(c)
                          for c in group["categories"][:]]
            codes = group["codes"][:]
            stage_group = handle["obs"]["Org_stage"]
            stage_categories = [c.decode() if isinstance(c, bytes) else str(c)
                                for c in stage_group["categories"][:]]
            stages = np.array([stage_categories[i] for i in stage_group["codes"][:]])
            labels = np.array([categories[i] for i in codes])
        mask = np.isin(stages, ["CS18-19", "CS20", "CS22-23"]) & (labels == "astroglia")
        counts["raw_human_cs_astroglia"] = int(mask.sum())
        rows.append({
            "check": "source_disagreement", "file": raw.name,
            "status": "EXPECTED",
            "expected": "raw matrices still say 'astroglia' for these cells",
            "observed": f"{int(mask.sum()):,} cells",
        })
    return rows, counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", required=True,
                        help="an arm config, e.g. config/arms/top500.yaml")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    config_path = Path(args.config).resolve()
    out = args.out or (REPO / "results" / "04_peak_regulatory" / "release_audit")
    out.mkdir(parents=True, exist_ok=True)

    print(f"[AUDIT] config {config_path}")
    manifest = load_manifest()

    rows = check_vendor(manifest)
    n_bad = sum(1 for row in rows if row["status"] != "OK")
    print(f"  vendor files: {len(rows)}, {n_bad} not OK")

    ranking_rows, files = check_rankings(config_path)
    rows += ranking_rows
    print(f"  ranking files seen by the Astroglia arm: {len(files)}")
    for name in files:
        print(f"    {name}")

    h5ad = Path(manifest["release_inputs"]["h5ad"])
    data_root = Path(manifest["release_inputs"]["data_root"])
    cell_rows, counts = check_cells(h5ad, data_root)
    rows += cell_rows
    for row in cell_rows:
        print(f"  [{row['status']}] {row['file']}: {row['observed']}")

    import pandas as pd

    frame = pd.DataFrame(rows)
    frame.to_csv(out / "audit_checks.tsv", sep="\t", index=False)

    # The one premise with a numeric consequence: each of the nine windows must
    # still have astroglia cells in the raw matrices, or the window is empty for
    # a second, unrelated reason.
    window_rows = []
    raw = data_root / "all_species_h5ad" / "human_deepcerevo_2026.h5ad"
    if raw.exists():
        import h5py
        import numpy as np

        with h5py.File(raw, "r") as handle:
            group = handle["obs"]["Org_Celltype"]
            categories = [c.decode() if isinstance(c, bytes) else str(c)
                          for c in group["categories"][:]]
            labels = np.array([categories[i] for i in group["codes"][:]])
            stage_group = handle["obs"]["Org_stage"]
            stage_categories = [c.decode() if isinstance(c, bytes) else str(c)
                                for c in stage_group["categories"][:]]
            stages = np.array([stage_categories[i] for i in stage_group["codes"][:]])
        for window, stage_list in (
            ("prenatal", ["11wpc", "15-17wpc"]),
            ("postnatal", ["newborn", "infant", "toddler"]),
            ("adult", ["adult", "adult_DN"]),
            ("early_embryonic", ["CS18-19", "CS20", "CS22-23"]),
        ):
            in_window = np.isin(stages, stage_list)
            window_rows.append({
                "window": window,
                "stages": "|".join(stage_list),
                "astroglia_cells_raw": int((in_window & (labels == "astroglia")).sum()),
                "in_this_release": window != "early_embryonic",
                "note": ("excluded: those cells are 'progenitor' in this release"
                         if window == "early_embryonic"
                         else "analysed"),
            })
    windows = pd.DataFrame(window_rows)
    windows.to_csv(out / "astroglia_windows.tsv", sep="\t", index=False)
    print("\n  astroglia windows (counts read from the still-stale raw matrix):")
    print(windows.to_string(index=False))

    summary = {
        "config": str(config_path),
        "vendor_files": len(rows),
        "vendor_not_ok": n_bad,
        "ranking_files": files,
        "ranking_excluded": EXCLUDED_RANKING,
        "counts": counts,
        "checks_failed": [r for r in rows if r["status"] in {"FAIL", "CHANGED", "MISSING",
                                                             "UNEXPECTED", "PRESENT"}],
    }
    (out / "release_audit.json").write_text(
        json.dumps(summary, indent=2, default=str) + "\n", encoding="utf-8"
    )

    if summary["checks_failed"]:
        print("\n[STOP] the audit found premises that do not hold:")
        for row in summary["checks_failed"]:
            print(f"  {row['status']}: {row['check']} / {row['file']} "
                  f"(expected {row['expected']}, observed {row['observed']})")
        return 1
    print(f"\n[DONE] all premises hold -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
